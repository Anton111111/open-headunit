package com.andrerinas.openheadunit.decoder.video.preflight

import androidx.annotation.RawRes
import com.andrerinas.openheadunit.R
import com.andrerinas.openheadunit.decoder.video.VideoDecoder
import com.andrerinas.openheadunit.utils.Settings

/**
 * One synthetic clip played by the onboarding video test.
 *
 * Every clip is a raw Annex B stream, not a container, because that is exactly what the decoder
 * receives from the phone. Each is five seconds at 30 fps, the rate these clips exercise, and
 * every frame carries its number in the corner so a dropped or reordered frame is visible in the
 * picture itself instead of only in a counter. The content is generated by `tools/preflight-clips`.
 */
data class VideoPreflightClip(
    val id: String,
    @RawRes val rawResource: Int,
    val codec: VideoDecoder.CodecType,
    val width: Int,
    val height: Int,
    val frameCount: Int = FRAME_COUNT,
    val fps: Int = FPS,
) {
    val marker: FrameMarker.Geometry get() = FrameMarker.geometryFor(width, height)
    val resolutionLabel: String get() = "${height}p"
    val label: String get() = "${codec.settingsValue} $resolutionLabel"

    companion object {
        const val FRAME_COUNT = 150
        const val FPS = 30

        val H264_480P = VideoPreflightClip(
            id = "h264-480p",
            rawResource = R.raw.preflight_h264_480p,
            codec = VideoDecoder.CodecType.H264,
            width = 800,
            height = 480,
        )
        val H264_720P = VideoPreflightClip(
            id = "h264-720p",
            rawResource = R.raw.preflight_h264_720p,
            codec = VideoDecoder.CodecType.H264,
            width = 1280,
            height = 720,
        )
        val H264_1080P = VideoPreflightClip(
            id = "h264-1080p",
            rawResource = R.raw.preflight_h264_1080p,
            codec = VideoDecoder.CodecType.H264,
            width = 1920,
            height = 1080,
        )
        val H265_1080P = VideoPreflightClip(
            id = "h265-1080p",
            rawResource = R.raw.preflight_h265_1080p,
            codec = VideoDecoder.CodecType.H265,
            width = 1920,
            height = 1080,
        )

        val ALL = listOf(H264_480P, H264_720P, H264_1080P, H265_1080P)
    }
}

/**
 * Chooses the clips worth playing for a panel.
 *
 * The list grows with the panel, so a 480p unit is not asked to decode 1080p only to be told it
 * cannot display it. H.265 is played when the panel is above Full HD, where Android Auto forces
 * it, or when the unit already stores H.265: an existing setting that produces artifacts is
 * exactly the case this test exists for.
 */
object VideoPreflightClips {

    fun forPanel(
        panelCeiling: Settings.Resolution,
        hevcSupported: Boolean,
        storedCodec: String,
        forceSoftware: Boolean,
    ): List<VideoPreflightClip> {
        val clips = mutableListOf(VideoPreflightClip.H264_480P)
        if (panelCeiling.height >= 720) clips += VideoPreflightClip.H264_720P
        if (panelCeiling.height >= 1080) clips += VideoPreflightClip.H264_1080P
        val wantsH265 = !forceSoftware &&
            (panelCeiling.height > 1080 || storedCodec.contains("265"))
        if (hevcSupported && wantsH265) clips += VideoPreflightClip.H265_1080P
        return clips
    }
}
